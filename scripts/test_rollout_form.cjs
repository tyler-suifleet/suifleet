const assert = require('node:assert/strict');
const fs = require('node:fs');
process.env.NEXT_PUBLIC_DEPLOYMENT_MANIFEST = fs.readFileSync('manifests/fixture.localnet.json','utf8');
const { loader, appRequire } = require('./frontend_test_utils.cjs');
const load = loader(), f = load('lib/rollout-form.ts'), r = load('lib/rollout.ts');
const version = { name:'pump', version:'2.0.0', manifests:[{recipeBlobId:'recipe',recipeSha256:'b'.repeat(64),artifactSha256:'a'.repeat(64)}] };
const input = {...f.libraryRecipe(version,0), cohorts:[['0x1'],['0x2','0x3']],concurrency:2,rateCount:3,minimumSamples:1};
const policy = f.policyInput(input,{rate:[30,'seconds'],bake:[5,'minutes'],stall:[2,'hours']},12.34);
assert.deepEqual([policy.rateWindowMs,policy.bakeMs,policy.offlineTimeoutMs,policy.failureBps],[30000,300000,7200000,1234]);
const data = r.buildRolloutTx(policy).getData();
const {bcs} = appRequire('@mysten/sui/bcs');
const decode=(arg,type)=>type.parse(Buffer.from(data.inputs[arg.Input].Pure.bytes,'base64'));
const policyCall = data.commands[0].MoveCall;
assert.deepEqual(policyCall.arguments.map(a=>decode(a,bcs.u64())),['2','3','30000','300000','1','1234','7200000']);
const create = data.commands[1].MoveCall;
assert.deepEqual(create.arguments.slice(0,5).map(a=>decode(a,bcs.string())),['pump','2.0.0','recipe','a'.repeat(64),'b'.repeat(64)]);
assert.deepEqual(decode(create.arguments[7],bcs.vector(bcs.u64())),['0','1','1']);
for (const bad of [NaN,Infinity,-1,101,0,0.001]) assert.throws(()=>f.policyInput(input,{rate:[1,'minutes'],bake:[0,'seconds'],stall:[1,'hours']},bad));
for (const bad of [NaN,Infinity,-1,604801]) assert.throws(()=>f.durationMs(bad,'seconds'));
assert.throws(()=>f.libraryRecipe(version,1));
assert.throws(()=>f.policyInput({...input,recipeSha256:'invalid'},{rate:[1,'minutes'],bake:[0,'seconds'],stall:[1,'hours']},10));
assert.throws(()=>f.policyInput({...input,cohorts:[['0x1'],['0x01']]},{rate:[1,'minutes'],bake:[0,'seconds'],stall:[1,'hours']},10));
const decision = {state:'Active',reason:'waiting for receipts, health or rate capacity',admitted:[]};
assert.match(f.decisionMessage(decision,0),/0 devices admitted.*No admission candidates were selected/);
assert.match(f.decisionMessage(decision,1),/0 devices admitted.*concurrency and rate capacity/);
assert.match(f.decisionMessage({...decision,admitted:['0x1']}),/1 device admitted.*Wait for device receipts/);
assert.match(f.decisionMessage({...decision,reason:'bake and health gate passed; next cohort'}),/Select candidates in the next cohort/);
assert.match(f.decisionMessage({...decision,reason:'baking completed cohort'}),/Wait for the bake period/);
assert.match(f.decisionMessage({...decision,state:'Paused'}),/resolve any blocking condition.*resuming/);
assert.match(f.decisionMessage({...decision,state:'Aborted'}),/No more devices can be admitted/);
assert.match(f.decisionMessage({...decision,reason:'deployment paused, cancelled or expired; no new grants'},0),/Review deployment control/);
assert.match(f.decisionMessage({...decision,state:'Complete'}),/All cohorts are complete/);
console.log('PASS rollout form: library recipe, exact transaction policy/cohort mapping, invalid inputs and decision next actions');
